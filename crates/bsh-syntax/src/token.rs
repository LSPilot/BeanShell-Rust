#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum FloatKind {
    Float,
    Double,
}

#[derive(Clone, Debug, PartialEq)]
pub enum TokenKind {
    Ident(String),
    /// Integer literal. The text keeps the original spelling (without suffix).
    Int {
        text: String,
        radix: u32,
        suffix: Option<char>,
    },
    /// Floating point literal; the text keeps the original spelling.
    Float {
        text: String,
        kind: FloatKind,
        big: bool,
    },
    Str(String),
    /// A single quoted literal. BeanShell allows more than one character and
    /// treats those as strings; both the raw and the unescaped text are kept.
    CharStr {
        raw: String,
        decoded: String,
    },
    Kw(Kw),

    LParen,
    RParen,
    LBrace,
    RBrace,
    LBracket,
    RBracket,
    Semi,
    Comma,
    Dot,
    Ellipsis,
    Colon,
    ColonColon,
    At,
    Arrow,
    Question,
    QuestionDot,

    Assign,
    Plus,
    Minus,
    Star,
    Slash,
    Percent,
    PlusPlus,
    MinusMinus,
    Eq,
    Ne,
    Lt,
    Gt,
    Le,
    Ge,
    AndAnd,
    OrOr,
    Not,
    Amp,
    Pipe,
    Caret,
    Tilde,
    Shl,
    Shr,
    Ushr,
    PlusAssign,
    MinusAssign,
    StarAssign,
    Power,
    PowerAssign,
    Spaceship,
    NullCoalesce,
    NullCoalesceAssign,
    Elvis,
    SlashAssign,
    PercentAssign,
    AmpAssign,
    PipeAssign,
    CaretAssign,
    ShlAssign,
    ShrAssign,
    UshrAssign,

    Eof,
}

impl TokenKind {
    /// Human readable spelling used in parse errors.
    pub fn describe(&self) -> String {
        use TokenKind::*;
        match self {
            Ident(s) => format!("identifier '{}'", s),
            Int { text, .. } => format!("integer literal '{}'", text),
            Float { text, .. } => format!("float literal '{}'", text),
            Str(_) => "string literal".to_string(),
            CharStr { decoded, .. } => format!("character literal '{}'", decoded),
            Kw(k) => format!("'{}'", k.text()),
            LParen => "'('".into(),
            RParen => "')'".into(),
            LBrace => "'{'".into(),
            RBrace => "'}'".into(),
            LBracket => "'['".into(),
            RBracket => "']'".into(),
            Semi => "';'".into(),
            Comma => "','".into(),
            Dot => "'.'".into(),
            Ellipsis => "'...'".into(),
            Colon => "':'".into(),
            ColonColon => "'::'".into(),
            At => "'@'".into(),
            Arrow => "'->'".into(),
            Question => "'?'".into(),
            QuestionDot => "'?.'".into(),
            Assign => "'='".into(),
            Plus => "'+'".into(),
            Minus => "'-'".into(),
            Star => "'*'".into(),
            Slash => "'/'".into(),
            Percent => "'%'".into(),
            PlusPlus => "'++'".into(),
            MinusMinus => "'--'".into(),
            Eq => "'=='".into(),
            Ne => "'!='".into(),
            Lt => "'<'".into(),
            Gt => "'>'".into(),
            Le => "'<='".into(),
            Ge => "'>='".into(),
            AndAnd => "'&&'".into(),
            OrOr => "'||'".into(),
            Not => "'!'".into(),
            Amp => "'&'".into(),
            Pipe => "'|'".into(),
            Caret => "'^'".into(),
            Tilde => "'~'".into(),
            Shl => "'<<'".into(),
            Shr => "'>>'".into(),
            Ushr => "'>>>'".into(),
            PlusAssign => "'+='".into(),
            MinusAssign => "'-='".into(),
            StarAssign => "'*='".into(),
            Power => "'**'".into(),
            PowerAssign => "'**='".into(),
            Spaceship => "'<=>'".into(),
            NullCoalesce => "'??'".into(),
            NullCoalesceAssign => "'??='".into(),
            Elvis => "'?:'".into(),
            SlashAssign => "'/='".into(),
            PercentAssign => "'%='".into(),
            AmpAssign => "'&='".into(),
            PipeAssign => "'|='".into(),
            CaretAssign => "'^='".into(),
            ShlAssign => "'<<='".into(),
            ShrAssign => "'>>='".into(),
            UshrAssign => "'>>>='".into(),
            Eof => "end of file".into(),
        }
    }
}

#[derive(Clone, Debug, PartialEq)]
pub struct Token {
    pub kind: TokenKind,
    pub span: Span,
}

impl Token {
    pub fn new(kind: TokenKind, span: Span) -> Self {
        Token { kind, span }
    }
}

impl fmt::Display for Token {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.kind.describe())
    }
}
